import type { Metadata } from "next";
import { BriefActions } from "@/components/care/BriefActions";
import { Card, PageHeader } from "@/components/ui";
import { requirePage } from "@/lib/auth/requirePage";
import { features } from "@/lib/env";
import { buildBrief } from "@/lib/services/brief";

export const metadata: Metadata = { title: "Doctor brief" };

/** Printable one-page summary for the doctor: adherence, misses, side effects, notes. */
export default async function BriefPage({ searchParams }: { searchParams: Promise<{ appointment?: string }> }) {
  const { circle } = await requirePage("brief:read");
  const { appointment } = await searchParams;
  const brief = await buildBrief(circle, appointment ?? null);

  return (
    <article className="space-y-5 print:space-y-3">
      <PageHeader
        title={`Doctor visit brief: ${brief.elderName}`}
        subtitle={`${brief.periodLabel}${brief.appointment ? ` · for ${brief.appointment.doctor}, ${brief.appointment.when}` : ""}`}
      />
      <BriefActions appointmentId={appointment ?? null} aiEnabled={features.ai()} />

      <Card>
        <h2 className="text-xl font-bold">Adherence (last 30 days)</h2>
        <p className="mt-1 text-lg">
          {brief.overall.percent === null ? "No doses due yet." : `${brief.overall.percent}% overall`} ·{" "}
          {brief.overall.taken} taken · {brief.overall.missed} missed · {brief.overall.skipped} skipped by choice
        </p>
        <table className="mt-3 w-full border-collapse text-left">
          <caption className="sr-only">Adherence by medicine</caption>
          <thead>
            <tr className="border-b border-line">
              <th scope="col" className="py-2">
                Medicine
              </th>
              <th scope="col" className="py-2">
                Schedule
              </th>
              <th scope="col" className="py-2">
                Adherence
              </th>
              <th scope="col" className="py-2">
                Missed
              </th>
            </tr>
          </thead>
          <tbody>
            {brief.medications.map((m) => (
              <tr key={m.name} className="border-b border-line align-top">
                <th scope="row" className="py-2 font-semibold">
                  {m.name} <span className="font-normal text-muted">{m.doseText}</span>
                </th>
                <td className="py-2">{m.times.join(", ")}</td>
                <td className="py-2">{m.adherence === null ? "–" : `${m.adherence}%`}</td>
                <td className="py-2">{m.missed}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </Card>

      <Card>
        <h2 className="text-xl font-bold">Missed doses and reasons</h2>
        {brief.missed.length === 0 ? (
          <p className="mt-1 text-muted">None in this period.</p>
        ) : (
          <ul className="mt-2 list-disc space-y-1 pl-6">
            {brief.missed.map((m, i) => (
              <li key={i}>
                {m.when}: {m.medName} ({m.reason})
              </li>
            ))}
          </ul>
        )}
      </Card>

      <Card>
        <h2 className="text-xl font-bold">Side effects and health notes</h2>
        {brief.symptoms.length === 0 ? (
          <p className="mt-1 text-muted">None reported.</p>
        ) : (
          <ul className="mt-2 list-disc space-y-1 pl-6">
            {brief.symptoms.map((s, i) => (
              <li key={i}>
                {s.when}
                {s.medName ? ` · ${s.medName}` : ""}: {s.text}
              </li>
            ))}
          </ul>
        )}
      </Card>

      {brief.appointment?.notes ? (
        <Card>
          <h2 className="text-xl font-bold">Notes for this visit</h2>
          <p className="mt-1">{brief.appointment.notes}</p>
        </Card>
      ) : null}

      <p className="text-sm text-muted">
        Generated by VridhaSuraksha from the family&apos;s own logs. It is a routine summary, not a medical assessment.
      </p>
    </article>
  );
}
